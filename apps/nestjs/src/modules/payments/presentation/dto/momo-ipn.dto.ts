import { IsInt, IsNumber, IsOptional, IsString } from 'class-validator';
import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';

export class MomoIpnDto {
  @ApiProperty({ description: 'MoMo partner code', example: 'MOMO' })
  @IsString()
  partnerCode: string;

  @ApiProperty({ description: 'Order ID / orderCode generated by SignTrustMap', example: 'STM-MOMO-1728000000-ABCDE' })
  @IsString()
  orderId: string;

  @ApiProperty({ description: 'Unique request ID for the transaction', example: 'REQ-1728000000' })
  @IsString()
  requestId: string;

  @ApiProperty({ description: 'Amount in VND', example: 50000 })
  @IsNumber()
  amount: number;

  @ApiProperty({ description: 'Order description/information', example: 'Top-up 50 credits' })
  @IsString()
  orderInfo: string;

  @ApiProperty({ description: 'Order type', example: 'momo_wallet' })
  @IsString()
  orderType: string;

  @ApiProperty({ description: 'MoMo transaction ID', example: 1234567890 })
  transId: number | string;

  @ApiProperty({ description: 'Result code: 0 indicates success', example: 0 })
  @IsInt()
  resultCode: number;

  @ApiProperty({ description: 'Human-readable result message', example: 'Thành công.' })
  @IsString()
  message: string;

  @ApiProperty({ description: 'Payment method type', example: 'qr' })
  @IsString()
  payType: string;

  @ApiProperty({ description: 'Response timestamp in milliseconds', example: 1728000000000 })
  @IsNumber()
  responseTime: number;

  @ApiPropertyOptional({ description: 'Extra data passed during creation' })
  @IsOptional()
  @IsString()
  extraData?: string;

  @ApiProperty({ description: 'HMAC-SHA256 signature generated by MoMo' })
  @IsString()
  signature: string;
}
